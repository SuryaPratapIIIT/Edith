function findGantry(id: string): RawGantry {
  const g = rawGantries.find(item => item.id === id);
  if (!g) {
    throw new Error(`Gantry ${id} not found in gantries.json`);
  }
  return g;
}

export const EXPRESSWAY_SECTIONS: EnforcementSection[] = SECTION_PAIRS.map(([startId, endId]) => {
  const g1 = findGantry(startId);
  const g2 = findGantry(endId);
  const pairKey = `${startId}_to_${endId}`;
  const polyline = HIGHWAY_POLYLINES[pairKey] || [
    [g1.lat, g1.lon],
    [g2.lat, g2.lon]
  ];
  const length_m = ROAD_DISTANCES[pairKey] || 3000;
  const displacement_m = Math.round(haversine_m([g1.lat, g1.lon], [g2.lat, g2.lon]));
  const detourPct = Number(((length_m / Math.max(1, displacement_m) - 1) * 100).toFixed(1));
  const limit = g1.limit_kmh;

  const vehicleLimits: Record<VehicleClass, number> = {
    car: limit,
    bike: Math.max(50, limit - 10),
    truck: Math.max(40, limit - 20)
  };

  return {
    id: `sec-${pairKey.toLowerCase()}`,
    name: `${g1.name} → ${g2.name}`,
    expressway: `${g1.road} (${g1.source} ANPR)`,
    startGantry: {
      id: g1.id,
      name: g1.name,
      lat: g1.lat,
      lon: g1.lon,
      direction: 'Manesar Bound (South-West)',
      kind: 'average',
      source: g1.source,
      verified_on: '2026-10-31'
    },
    endGantry: {
      id: g2.id,
      name: g2.name,
      lat: g2.lat,
      lon: g2.lon,
      direction: 'Manesar Bound (South-West)',
      kind: 'average',
      source: g2.source,
      verified_on: '2026-10-31'
    },
    length_m,
    displacement_m,
    detourPct,
    limit_kmh: limit,
    vehicleLimits,
    laneNote: `${g1.road} ANPR speed corridor. Sectional speed enforcement: ${limit} km/h limit.`,
    polyline,
    source: g1.source,
    verified_on: '2026-10-31'
  };
});
